from __future__ import annotations

from collections.abc import Iterable, Sequence


def pack_u16(value: int) -> bytes:
    return bytes([(value >> 8) & 0xFF, value & 0xFF])


def dedupe_bytes(values: Iterable[bytes]) -> tuple[bytes, ...]:
    seen: set[bytes] = set()
    ordered: list[bytes] = []
    for value in values:
        if value in seen:
            continue
        seen.add(value)
        ordered.append(value)
    return tuple(ordered)


def escape_bytes(value: bytes) -> str:
    return ''.join(f'\\x{byte:02x}' for byte in value)


def render_afl_dictionary(entries: Sequence[bytes]) -> str:
    return '\n'.join(f'"{escape_bytes(entry)}"' for entry in entries)


